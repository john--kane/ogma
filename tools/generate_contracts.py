#!/usr/bin/env python3
"""Generate ABI, strict IPC types, schema, and guest bindings from one source."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
contract = json.loads((ROOT / 'contracts/ogma.json').read_text())

def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()

def pascal(name):
    return name[0].upper() + name[1:]

def mapped(kind, scalars, array):
    return array(mapped(kind[:-2], scalars, array)) if kind.endswith('[]') else scalars.get(kind, kind)

rs = ['// Generated by tools/generate_contracts.py. Do not edit.',
      'use serde::{Deserialize, Serialize};',
      f'pub const PROTOCOL_VERSION: u32 = {contract["protocolVersion"]};',
      f'pub const ABI_VERSION: u32 = {contract["abiVersion"]};',
      f'pub const MAX_FRAME_BYTES: usize = {contract["maxFrameBytes"]};',
      '#[repr(u32)]', '#[derive(Debug, Clone, Copy, PartialEq, Eq)]', 'pub enum Status {']
rs += [f'    {pascal(name)} = {value},' for name, value in contract['statuses'].items()]
rs += ['}']
cs = ['// Generated by tools/generate_contracts.py. Do not edit.',
      'using System.Runtime.InteropServices;', 'using System.Text.Json.Serialization;',
      'namespace Ogma;', 'public static class Contract {',
      f'    public const uint ProtocolVersion = {contract["protocolVersion"]};',
      f'    public const uint AbiVersion = {contract["abiVersion"]};',
      f'    public const int MaxFrameBytes = {contract["maxFrameBytes"]};',
      f'    public const int MaxMcpTools = {contract["mcp"]["maxTools"]};',
      '    public static readonly string[] McpProtocolVersions = [' + ', '.join(json.dumps(v) for v in contract['mcp']['protocolVersions']) + '];', '}',
      'public enum Status : uint {']
cs += [f'    {pascal(name)} = {value},' for name, value in contract['statuses'].items()]
cs += ['}']
schema = {'$schema': 'https://json-schema.org/draft/2020-12/schema',
          '$id': f'https://ogma.dev/schemas/protocol-v{contract["protocolVersion"]}.json',
          'oneOf': [{'$ref': '#/$defs/Request'}, {'$ref': '#/$defs/Response'}], '$defs': {}}
ts = ['// Generated by tools/generate_contracts.py. Do not edit.',
      f'export declare const protocolVersion: {contract["protocolVersion"]};',
      f'export declare const abiVersion: {contract["abiVersion"]};',
      'export declare const Status: {']
ts += [f'  readonly {pascal(name)}: {value};' for name, value in contract['statuses'].items()]
ts += ['};', 'export type Status = typeof Status[keyof typeof Status];']
protocol_js = ['// Generated by tools/generate_contracts.py. Do not edit.',
               f'export const protocolVersion = {contract["protocolVersion"]};',
               f'export const abiVersion = {contract["abiVersion"]};',
               'export const Status = Object.freeze(' + json.dumps({pascal(k): v for k, v in contract['statuses'].items()}, indent=2) + ');']
for name, fields in contract['types'].items():
    rs += ['#[derive(Debug, Clone, Default, Serialize, Deserialize)]',
           '#[serde(rename_all = "camelCase", deny_unknown_fields)]', f'pub struct {name} {{']
    cs += ['[JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]', f'public sealed record {name} {{']
    properties = {}
    ts += [f'export interface {name} {{']
    for field, kind in fields.items():
        rs_type = mapped(kind, {'uint': 'u32', 'int': 'i32', 'ulong': 'u64', 'string': 'String', 'bool': 'bool', 'json': 'serde_json::Value'}, lambda x: f'Vec<{x}>')
        cs_type = mapped(kind, {'uint': 'uint', 'ulong': 'ulong', 'string': 'string', 'bool': 'bool', 'json': 'System.Text.Json.JsonElement?'}, lambda x: x + '[]')
        default = '[]' if kind.endswith('[]') else '""' if kind == 'string' else 'null' if kind == 'json' else 'false' if kind == 'bool' else '0' if kind in ('uint', 'ulong', 'int') else 'new()'
        rs += [f'    pub {snake(field)}: {rs_type},']
        cs += ['    [JsonRequired]', f'    public {cs_type} {pascal(field)} {{ get; init; }} = {default};']
        ts_type = mapped(kind, {'uint': 'number', 'int': 'number', 'ulong': 'number', 'string': 'string', 'bool': 'boolean', 'json': 'unknown'}, lambda x: x + '[]')
        ts += [f'  {field}: {ts_type};']
        def prop(k):
            if k.endswith('[]'):
                return {'type': 'array', 'items': prop(k[:-2])}
            if k in ('uint', 'ulong'):
                return {'type': 'integer', 'minimum': 0, 'maximum': 2**(32 if k == 'uint' else 64)-1}
            if k == 'int':
                return {'type': 'integer', 'minimum': -(2**31), 'maximum': 2**31-1}
            if k == 'json':
                return {}
            if k in ('string', 'bool'):
                return {'type': 'boolean' if k == 'bool' else k}
            return {'$ref': '#/$defs/' + k}
        properties[field] = prop(kind)
        if field == "protocolVersion":
            properties[field]["const"] = contract["protocolVersion"]
    rs += ['}']
    cs += ['}']
    ts += ['}']
    schema['$defs'][name] = {'type': 'object', 'additionalProperties': False,
                            'required': list(fields), 'properties': properties}
cs += ['[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase, RespectNullableAnnotations = true)]']
cs += [f'[JsonSerializable(typeof({name}))]' for name in contract['types']]
cs += ['internal partial class ProtocolJson : JsonSerializerContext {}',
       'internal static unsafe partial class NativeMethods {']
header = ['/* Generated by tools/generate_contracts.py. Do not edit. */',
          '#ifndef OGMA_ABI_H', '#define OGMA_ABI_H', '#include <stdint.h>', '#include <stddef.h>',
          '#ifdef _WIN32', '#define OGMA_API __declspec(dllimport)', '#else', '#define OGMA_API', '#endif',
          '#ifdef __cplusplus', 'extern "C" {', '#endif',
          f'#define OGMA_ABI_VERSION {contract["abiVersion"]}',
          'typedef uint64_t ogma_handle;', 'typedef enum ogma_status {']
header += [f'    OGMA_{snake(name).upper()} = {value},' for name, value in contract['statuses'].items()]
header += ['} ogma_status;']
c_types = {'uint': 'uint32_t', 'status': 'ogma_status', 'handle': 'ogma_handle',
           'handleOut': 'ogma_handle*', 'bytes': 'uint8_t*', 'size': 'size_t', 'sizeOut': 'size_t*'}
cs_abi = {'uint': 'uint', 'status': 'Status', 'handle': 'ulong', 'handleOut': 'out ulong',
          'bytes': 'byte*', 'size': 'nuint', 'sizeOut': 'out nuint'}
rs_abi = {'uint': 'u32', 'status': 'Status', 'handle': 'u64', 'handleOut': '*mut u64',
          'bytes': '*mut u8', 'size': 'usize', 'sizeOut': '*mut usize'}
rs += ['// Function pointer types keep implementations checked against the shared ABI.']
for function in contract['abi']:
    name, params, result = function['name'], function['params'], function['return']
    cs += [f'    [LibraryImport("ogma_runtime", EntryPoint = "{name}")]',
           '    [UnmanagedCallConv(CallConvs = [typeof(System.Runtime.CompilerServices.CallConvCdecl)])]',
           f'    internal static partial {cs_abi[result]} {pascal(name)}({", ".join(cs_abi[t] + " " + n for n,t in params)});']
    header += [f'OGMA_API {c_types[result]} {name}({", ".join(c_types[t] + " " + n for n,t in params) or "void"});']
    rs += [f'pub type {pascal("".join(pascal(x) for x in name.split("_")))}Fn = unsafe extern "C" fn({", ".join(rs_abi[t] for _,t in params)}) -> {rs_abi[result]};']
cs += ['}']
header += ['#ifdef __cplusplus', '}', '#endif', '#endif']
js = ['// Generated by tools/generate_contracts.py. Do not edit.', '(() => {',
      '  const native = globalThis.__ogmaHost;' , '  delete globalThis.__ogmaHost;',
      '  const render = x => typeof x === "string" ? x : typeof x === "bigint" ? `${x}n` : typeof x === "undefined" ? "undefined" : (() => { try { return JSON.stringify(x) ?? String(x); } catch { return String(x); } })();',
      '  globalThis.console = Object.freeze(Object.fromEntries(["log", "info", "warn", "error", "debug"].map(name => [name, (...args) => native("print", name === "error" || name === "warn" ? "stderr" : "stdout", args.map(render).join(" "))])));',
      '  const tests = [];',
      (ROOT / 'tools/templates/mcp-bootstrap.js').read_text().replace('@@REGISTRATION@@', contract['mcp']['registration']).replace('@@MAX_TOOLS@@', str(contract['mcp']['maxTools'])),
      '  const api = {',
      f'    {contract["mcp"]["registration"]},',
      '    args: Object.freeze(native("args")),',
      '    test(name, fn) { if (typeof name !== "string" || typeof fn !== "function") throw new TypeError("test requires a name and function"); tests.push({ name, fn }); },']
dts = ['// Generated by tools/generate_contracts.py. Do not edit.', 'declare namespace Ogma {',
       '  const args: readonly string[];', '  function test(name: string, fn: () => void | Promise<void>): void;',
       f'  function {contract["mcp"]["registration"]}(definition: import("./protocol.js").McpTool, handler: (args: Record<string, unknown>) => string | Promise<string>): void;']
for api in contract['apis']:
    names = ', '.join(n for n,_ in api['params'])
    signature = ', '.join(n + (' = ""' if n in api.get('optional', []) else '') for n,_ in api['params'])
    validation = ' '.join(f'if (typeof {n} !== "{t}") throw new TypeError("{n} must be {t}");' for n,t in api['params'])
    call = f'native("{api["name"]}", {names})' + (' ?? undefined' if api['name'] == 'env' else '')
    if api.get('decode') == 'json': call = f'JSON.parse(await {call})'
    js += [f'    {"async " if api["async"] else ""}{api["name"]}({signature}) {{ {validation} return {call}; }},']
    dts += [f'  function {api["name"]}({", ".join(n+("?" if n in api.get("optional", []) else "")+": "+t for n,t in api["params"])}): {api["result"]};']
js += ['  };', '  globalThis.Ogma = Object.freeze(api);',
       '  globalThis.__ogmaRunTests = async () => { for (const { name, fn } of tests) { await fn(); console.log(`ok ${name}`); } return tests.length; };',
       '})();']
dts += ['}', 'interface OgmaConsole {',
        *[f'  {name}(...values: unknown[]): void;' for name in ['log', 'info', 'warn', 'error', 'debug']],
        '}', 'declare const console: OgmaConsole;']
outputs = {
    'crates/ogma-runtime/src/mcp_scaffold.ts': (ROOT / 'tools/templates/mcp-server.ts').read_text().replace('@@REGISTRATION@@', contract['mcp']['registration']),
    'crates/ogma-runtime/src/generated.rs': '\n'.join(rs)+'\n',
    'src/Ogma.Cli/Generated.cs': '\n'.join(cs)+'\n',
    'contracts/ogma.h': '\n'.join(header)+'\n',
    f'contracts/protocol-v{contract["protocolVersion"]}.schema.json': json.dumps(schema, indent=2)+'\n',
    'crates/ogma-runtime/src/bootstrap.js': '\n'.join(js)+'\n',
    'types/ogma.d.ts': '\n'.join(dts)+'\n',
    'types/protocol.d.ts': '\n'.join(ts)+'\n',
    'types/protocol.js': '\n'.join(protocol_js)+'\n',
}
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
failed = False
for path, content in outputs.items():
    target = ROOT / path
    if args.check:
        if not target.exists() or target.read_text() != content:
            print('generated contract drift:', path)
            failed = True
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text() != content:
            target.write_text(content)
raise SystemExit(1 if failed else 0)
